static esp_err_t send_json(httpd_req_t *req, cJSON *root) {
    char *out = cJSON_PrintUnformatted(root);
    cJSON_Delete(root);
    if (!out) return ESP_ERR_NO_MEM;
    httpd_resp_set_type(req, "application/json");
    httpd_resp_set_hdr(req, "Cache-Control", "no-store");
    esp_err_t err = httpd_resp_send(req, out, strlen(out));
    free(out);
    return err;
}

static esp_err_t send_err(httpd_req_t *req, int code, const char *msg) {
    char body[128];
    snprintf(body, sizeof(body), "{\"error\":\"%s\"}", msg);
    httpd_resp_set_type(req, "application/json");
    httpd_resp_set_status(req,
        code == 400 ? "400 Bad Request" :
        code == 401 ? "401 Unauthorized" :
        code == 404 ? "404 Not Found" :
        code == 500 ? "500 Internal Server Error" :
        "500 Internal Server Error");
    return httpd_resp_send(req, body, strlen(body));
}

static cJSON *read_body_json(httpd_req_t *req) {
    if (req->content_len == 0 || req->content_len > 4096) return NULL;
    char *buf = malloc(req->content_len + 1);
    if (!buf) return NULL;
    int got = 0;
    while (got < (int)req->content_len) {
        int n = httpd_req_recv(req, buf + got, req->content_len - got);
        if (n <= 0) { free(buf); return NULL; }
        got += n;
    }
    buf[got] = 0;
    cJSON *j = cJSON_Parse(buf);
    free(buf);
    return j;
}

static bool extract_session_token(httpd_req_t *req, char *out, size_t max) {
    char hdr[256];
    if (httpd_req_get_hdr_value_str(req, "Cookie", hdr, sizeof(hdr)) != ESP_OK) return false;
    /* Find ambisense=<hex> */
    const char *p = strstr(hdr, "ambisense=");
    if (!p) return false;
    p += strlen("ambisense=");
    size_t i = 0;
    while (*p && *p != ';' && *p != ' ' && i < max - 1) out[i++] = *p++;
    out[i] = 0;
    return i > 0;
}

static bool gate_auth(httpd_req_t *req) {
    if (!auth_is_enabled()) return true;
    char tok[AUTH_TOKEN_HEX_LEN + 1];
    if (!extract_session_token(req, tok, sizeof(tok))) {
        send_err(req, 401, "auth required");
        return false;
    }
    if (!auth_check_session(tok)) {
        send_err(req, 401, "invalid session");
        return false;
    }
    return true;
}

/* ============================================================
 *  Captive-portal redirect endpoints
 *
 *  iOS hits captive.apple.com / hotspot-detect.html / library/test/...
 *  Android hits connectivitycheck.gstatic.com / generate_204
 *  Win 11 hits msftconnecttest.com/connecttest.txt
 *  All return a 302 redirect to our root so the OS pops the setup page.
 * ============================================================ */

static esp_err_t handle_captive_redirect(httpd_req_t *req) {
    char ip[32] = "192.168.4.1";
    netmgr_get_ip(ip, sizeof(ip));
    char loc[64];
    snprintf(loc, sizeof(loc), "http://%s/", ip);
    httpd_resp_set_status(req, "302 Found");
    httpd_resp_set_hdr(req, "Location", loc);
    httpd_resp_set_hdr(req, "Cache-Control", "no-store");
    httpd_resp_send(req, NULL, 0);
    return ESP_OK;
}

/* ============================================================
 *  Root — serves the embedded gzipped Preact UI built from
 *  frontend/. The blob lives in main/ui.html.gz, embedded via the
 *  EMBED_FILES directive in main/CMakeLists.txt. Symbols below are
 *  generated by the IDF build.
 * ============================================================ */

extern const uint8_t _binary_ui_html_gz_start[] asm("_binary_ui_html_gz_start");
extern const uint8_t _binary_ui_html_gz_end[]   asm("_binary_ui_html_gz_end");
extern const uint8_t _binary_ui_html_start[]    asm("_binary_ui_html_start");
extern const uint8_t _binary_ui_html_end[]      asm("_binary_ui_html_end");

/* Serve the embedded UI, sniffing Accept-Encoding so clients that don't
 * advertise gzip support get the raw HTML. Some captive-portal detects and
 * a small handful of mobile browser edge cases strip Accept-Encoding for
 * private-network LAN requests; serving raw to those keeps the UI working. */
static esp_err_t handle_root_real(httpd_req_t *req) {
    char ae[80] = {0};
    bool accepts_gzip = false;
    if (httpd_req_get_hdr_value_str(req, "Accept-Encoding", ae, sizeof(ae)) == ESP_OK) {
        accepts_gzip = (strstr(ae, "gzip") != NULL);
    }

    httpd_resp_set_type(req, "text/html; charset=utf-8");
    httpd_resp_set_hdr(req, "Cache-Control", "max-age=300, public");

    /* esp_http_server's single-call httpd_resp_send truncates ~16KB responses
     * on the C3 because the underlying tx buffer can't accept it all at once.
     * Break large bodies into chunks. Tested: 50 KB raw HTML now delivers
     * intact instead of cutting off at ~15.8 KB. */
    const uint8_t *body;
    size_t total;
    if (accepts_gzip) {
        httpd_resp_set_hdr(req, "Content-Encoding", "gzip");
        body  = _binary_ui_html_gz_start;
        total = _binary_ui_html_gz_end - _binary_ui_html_gz_start;
    } else {
        body  = _binary_ui_html_start;
        total = _binary_ui_html_end - _binary_ui_html_start;
    }

    const size_t CHUNK = 4096;
    size_t sent = 0;
    while (sent < total) {
        size_t n = total - sent;
        if (n > CHUNK) n = CHUNK;
        esp_err_t err = httpd_resp_send_chunk(req, (const char *)(body + sent), n);
        if (err != ESP_OK) return err;
        sent += n;
    }
    return httpd_resp_send_chunk(req, NULL, 0);   /* terminator */
}

