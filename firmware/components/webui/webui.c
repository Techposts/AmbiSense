        if (!p) continue;
        cJSON *o = cJSON_CreateObject();
        cJSON_AddStringToObject(o, "id", p->id);
        cJSON_AddStringToObject(o, "display", p->display);
        cJSON_AddStringToObject(o, "mcu", p->mcu);
        cJSON_AddBoolToObject (o, "validated", p->validated);
